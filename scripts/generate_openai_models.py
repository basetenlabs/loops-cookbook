"""Generate the Chat Completions schema models from one pinned OpenAI OpenAPI revision.

The gateway's request, response, and stream-chunk types are generated, not written
by hand, from the official ``openai/openai-openapi`` source at ``REVISION``. This
script extracts the schemas those three documents reach, commits that extract with
its digest, and generates pydantic models from it::

    # refresh from the pinned upstream revision (network), or from a local copy of it
    uv run python scripts/generate_openai_models.py [--source openapi.json]

    # release gate: offline, nonzero when the committed output is stale
    uv run python scripts/generate_openai_models.py --check

Moving to a newer revision means changing ``REVISION`` and ``SOURCE_SHA256``
together, then regenerating; the capability matrix tests say what else must follow.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path
from typing import Any

REVISION = "7de0436e058814c8fab9bf18b60208e5f79762d3"
SOURCE_URL = f"https://raw.githubusercontent.com/openai/openai-openapi/{REVISION}/openapi.json"
SOURCE_SHA256 = "a85ddf06d773a36c2c3cce0ae690bc5124dc6ba1b664730bceda94c35cd368a7"
ROOTS = (
    "CreateChatCompletionRequest",
    "CreateChatCompletionResponse",
    "CreateChatCompletionStreamResponse",
)

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_DIR = ROOT / "src" / "loops_cookbook" / "model_access" / "openai" / "schema"
EXTRACT = SCHEMA_DIR / "chat_completions.json"
MODELS = SCHEMA_DIR / "models.py"

GENERATOR_OPTIONS = (
    "--input-file-type=openapi",
    "--output-model-type=pydantic_v2.BaseModel",
    "--target-python-version=3.12",
    "--use-union-operator",
    "--use-standard-collections",
    "--use-annotated",
    "--field-constraints",
    "--enum-field-as-literal=all",
    "--collapse-root-models",
    "--disable-timestamp",
    # Unknown fields are kept rather than dropped, so the capability policy can
    # reject each one by name instead of ignoring it.
    "--allow-extra-fields",
)


def _digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def extract(document: dict[str, Any]) -> dict[str, Any]:
    """The Chat Completions roots and every schema they reference, and nothing else."""
    schemas: dict[str, Any] = document["components"]["schemas"]
    reached: set[str] = set(ROOTS)
    pending = [schemas[name] for name in ROOTS]
    while pending:
        node = pending.pop()
        if isinstance(node, dict):
            ref = node.get("$ref")
            if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
                name = ref.removeprefix("#/components/schemas/")
                if name not in reached:
                    reached.add(name)
                    pending.append(schemas[name])
            pending.extend(node.values())
        elif isinstance(node, list):
            pending.extend(node)
    selected = {name: _nullable(schemas[name]) for name in sorted(reached)}
    return {
        "openapi": document["openapi"],
        "info": {
            "title": document["info"]["title"],
            "version": document["info"]["version"],
            "x-loops-source": {"url": SOURCE_URL, "sha256": SOURCE_SHA256},
        },
        "paths": {},
        "components": {"schemas": selected},
    }


def _nullable(node: Any) -> Any:
    """OpenAPI 3.0's ``nullable: true``, spelled as 3.1's ``null`` alternative.

    The upstream document declares 3.1 but still uses the 3.0 keyword in places,
    which 3.1 tooling ignores; without this, fields the document calls nullable,
    such as a stream chunk's ``finish_reason``, would be generated as required.
    """
    if isinstance(node, list):
        return [_nullable(item) for item in node]
    if not isinstance(node, dict):
        return node
    result = {key: _nullable(value) for key, value in node.items() if key != "nullable"}
    if node.get("nullable") is not True:
        return result
    for union in ("anyOf", "oneOf"):
        if union in result:
            if {"type": "null"} not in result[union]:
                result[union] = [*result[union], {"type": "null"}]
            return result
    if isinstance(result.get("type"), str):
        if "enum" in result:
            result["enum"] = [*result["enum"], None]
        result["type"] = [result["type"], "null"]
        return result
    annotations = {k: result.pop(k) for k in ("description", "default", "title") if k in result}
    return {**annotations, "anyOf": [result, {"type": "null"}]}


def _extract_bytes(document: dict[str, Any]) -> bytes:
    return (json.dumps(extract(document), indent=1, sort_keys=True) + "\n").encode()


def _header(extract_digest: str) -> str:
    return (
        "# Generated by scripts/generate_openai_models.py; do not edit.\n"
        f"# Source: {SOURCE_URL}\n"
        f"# Source sha256: {SOURCE_SHA256}\n"
        f"# Extract sha256: {extract_digest}\n"
        "# pyright: basic\n"
        # The generator gives a union's null default to its list member (StopConfiguration1).
        "# pyright: reportAssignmentType=false\n"
    )


def generate(extract_path: Path) -> str:
    """Models for the extract at ``extract_path``, exactly as they are committed."""
    with tempfile.TemporaryDirectory() as directory:
        output = Path(directory) / "models.py"
        subprocess.run(
            [
                sys.executable,
                "-m",
                "datamodel_code_generator",
                f"--input={extract_path}",
                f"--output={output}",
                *GENERATOR_OPTIONS,
            ],
            check=True,
            capture_output=True,
        )
        body = output.read_text()
    return _header(_digest(extract_path.read_bytes())) + body


def _source(path: Path | None) -> bytes:
    if path is not None:
        data = path.read_bytes()
    else:
        with urllib.request.urlopen(SOURCE_URL, timeout=60) as response:
            data = response.read()
    if (found := _digest(data)) != SOURCE_SHA256:
        raise SystemExit(f"source digest {found} does not match the pinned {SOURCE_SHA256}")
    return data


def check() -> list[str]:
    """What is stale about the committed extract and models; empty when current."""
    problems = []
    data = EXTRACT.read_bytes()
    info = json.loads(data)["info"]["x-loops-source"]
    if info != {"url": SOURCE_URL, "sha256": SOURCE_SHA256}:
        problems.append(f"{EXTRACT.name} records source {info}, not the pinned revision")
    if not MODELS.read_text().startswith(_header(_digest(data))):
        problems.append(f"{MODELS.name} was not generated from the committed {EXTRACT.name}")
    elif generate(EXTRACT) != MODELS.read_text():
        problems.append(f"{MODELS.name} differs from what the generator produces")
    return problems


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true", help="verify offline; change nothing")
    group.add_argument("--source", type=Path, help="a local copy of the pinned openapi.json")
    args = parser.parse_args()
    if args.check:
        if problems := check():
            raise SystemExit("\n".join(problems))
        return
    SCHEMA_DIR.mkdir(parents=True, exist_ok=True)
    EXTRACT.write_bytes(_extract_bytes(json.loads(_source(args.source))))
    MODELS.write_text(generate(EXTRACT))


if __name__ == "__main__":
    main()
